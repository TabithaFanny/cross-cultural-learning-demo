function sourcePanel(title, sources, variant = "") {
  if (!sources.length) return "";
  const desc = activeLang === "en"
    ? "The demo has mapped public sources. Before launch, add local expert review, enterprise HR / legal review, and real business-team validation."
    : "内容基于公开资料、真实案例和企业场景整理，适合作为学习与讨论材料。";
  const auditLabels = activeLang === "en"
    ? ["Public sources", "Real cases", "Business scenarios"]
    : ["公开资料", "真实案例", "企业场景"];

  return `
    <section class="detail-section source-panel ${escapeHtml(variant)}">
      <h3>${displayText(title)}</h3>
      <p>${escapeHtml(desc)}</p>
      <div class="source-list">
        ${sources
          .map(
            (source) => `
              <a href="${escapeHtml(source.url)}" target="_blank" rel="noreferrer">
                <span>Source</span>
                <strong>${displayText(source.label)}</strong>
              </a>
            `
          )
          .join("")}
      </div>
      <div class="audit-strip">
        ${auditLabels.map((label) => `<span>${escapeHtml(label)}</span>`).join("")}
      </div>
    </section>
  `;
}

