function clampScore(value) {
  return Math.max(0, Math.min(100, Math.round(value)));
}

function includesAny(text, words) {
  return words.some((word) => text.includes(word));
}

function detectScenarioType(text) {
  const currentStep = scenario[scenarioStep]?.ai || scenario[Math.max(0, scenarioStep - 1)]?.ai || "";
  const source = `${currentStep} ${text}`;

  if (includesAny(source, ["反馈", "批评", "绩效", "主管", "员工"])) return "反馈与改进";
  if (includesAny(source, ["延期", "供应商", "清关", "交付", "客户", "物料"])) return "进度风险与供应商协作";
  if (includesAny(source, ["沉默", "没人", "反对", "会上", "会议"])) return "会议表达与风险确认";
  if (includesAny(source, ["首次", "开场", "认识", "信任", "寒暄", "咖啡"])) return "首次会议与关系建立";
  if (includesAny(source, ["生活", "通勤", "住宿", "医疗", "支付", "安全"])) return "外派生活适应";
  return "跨团队协作沟通";
}

function scoreFreeResponse(text, scenarioType) {
  const respectful = ["感谢", "理解", "辛苦", "一起", "支持", "请", "方便", "尊重", "先确认", "我们"];
  const risk = ["风险", "卡点", "依赖", "条件", "影响", "原因", "预警", "不确定", "如果", "升级"];
  const action = ["时间", "负责人", "节点", "下一步", "会后", "书面", "同步", "确认", "方案", "明天", "今天"];
  const culture = ["私下", "一对一", "层级", "本地", "信任", "面子", "礼貌", "低压力", "关系", "越南"];
  const harsh = ["必须", "立刻", "马上", "不专业", "责任", "点名", "公开批评", "为什么没", "直接要求"];

  const penalty = includesAny(text, harsh) ? 14 : 0;
  const tone = clampScore(54 + respectful.filter((word) => text.includes(word)).length * 8 - penalty);
  const riskScore = clampScore(48 + risk.filter((word) => text.includes(word)).length * 9 - (includesAny(text, ["没问题", "不用", "相信"]) ? 8 : 0));
  const actionScore = clampScore(50 + action.filter((word) => text.includes(word)).length * 8 - (text.length < 18 ? 12 : 0));
  const cultureScore = clampScore(50 + culture.filter((word) => text.includes(word)).length * 9 + (scenarioType.includes("反馈") ? 4 : 0) - penalty);

  return {
    tone,
    risk: riskScore,
    action: actionScore,
    culture: cultureScore
  };
}

