function setProgressMetric(key, value) {
  const normalized = Math.max(0, Math.min(100, Math.round(Number(value) || 0)));
  const valueNode = document.querySelector(`[data-progress-value="${key}"]`);
  const barNode = document.querySelector(`[data-progress-bar="${key}"]`);
  if (valueNode) valueNode.textContent = `${normalized}%`;
  if (barNode) barNode.style.width = `${normalized}%`;
}

