function relatedCardsForModule(module) {
  const explicitIds = module.relatedCards || [];
  const embeddedIds = ["topics", "mistakes", "exercises"]
    .flatMap((key) => module[key] || [])
    .map((item) => item.id)
    .filter(Boolean);
  const uniqueIds = [...new Set([...explicitIds, ...embeddedIds])];

  if (uniqueIds.length) {
    return uniqueIds
      .map((id) => {
        const index = findCardIndexById(id);
        return index >= 0 ? { ...cards[index], index } : null;
      })
      .filter(Boolean);
  }

  return cards
    .map((card, index) => ({ ...card, index }))
    .filter((card) => card.moduleNo === module.no);
}

