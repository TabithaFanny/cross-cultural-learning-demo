function renderScenarioStep() {
  choiceRow.innerHTML = "";
  const step = scenario[scenarioStep];

  if (!step) {
    appendMessage("ai", isEnglishMode() ? `Training completed. You can now better handle tasks, relationships, and risk confirmation in China-${displayCountryPack().country} collaboration.` : `训练完成。你已经能更好地处理中国与${activeCountryPack().country}团队协作中的任务、关系和风险确认。`);
    demoState.scenarioCompleted = true;
    demoState.scenarioScore = score;
    demoState.lastInsight = score >= 70
      ? (isEnglishMode() ? "Employee can reduce cross-cultural misreads through polite follow-up, condition confirmation, and written recap." : "员工已能用礼貌追问、条件确认和书面复盘降低跨文化误读")
      : (isEnglishMode() ? "Employee may still become too direct under pressure and needs more feedback and risk-confirmation practice." : "员工在压力场景下仍可能过度直接，需要继续训练反馈方式和风险确认");
    updateEnterpriseDashboard();
    choiceRow.innerHTML = `<button data-action="reset">${isEnglishMode() ? "Practice again" : "再练一次"}</button>`;
    return;
  }

  const displayStep = translateValue(step);
  appendMessage("ai", displayStep.ai);
  step.choices.forEach((choice) => {
    const displayChoice = translateValue(choice);
    const button = document.createElement("button");
    button.textContent = displayChoice.text;
    button.addEventListener("click", () => {
      appendMessage("user", displayChoice.text);
      scenarioFreeInput.value = choice.text;
      score = Math.max(0, Math.min(100, score + choice.score));
      readinessScore.textContent = `${score}%`;
      demoState.scenarioScore = score;
      demoState.lastInsight = choice.score > 0
        ? (isEnglishMode() ? "Positive behavior in scenario practice: confirm relationship, conditions, and support before pushing tasks." : "场景训练中出现正向行为：先确认关系、条件和支持，再推进任务")
        : (isEnglishMode() ? "Risky behavior in scenario practice: HQ pressure may be pushed directly onto the local team." : "场景训练中出现风险行为：可能把总部速度直接压到本地团队");
      updateEnterpriseDashboard();
      appendMessage("ai", displayChoice.reply);
      scenarioStep += 1;
      setTimeout(renderScenarioStep, 500);
    });
    choiceRow.appendChild(button);
  });
}

function resetScenario() {
  scenarioStep = 0;
  score = 42;
  readinessScore.textContent = `${score}%`;
  demoState.scenarioCompleted = false;
  demoState.scenarioScore = score;
  demoState.lastInsight = isEnglishMode() ? "Scenario practice reset. Waiting for a new collaboration practice round." : "已重置场景训练，等待员工完成新一轮协作演练";
  updateEnterpriseDashboard();
  chatWindow.innerHTML = "";
  resetScenarioAnalysis();
  renderScenarioStep();
}

