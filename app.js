function translateValue(value) {
  if (activeLang !== "en") return value;
  if (typeof value === "string") return translateText(value);
  if (Array.isArray(value)) return value.map((item) => translateValue(item));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateValue(item)]));
  }
  return value;
}

