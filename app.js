async function generateContent() {
  const country = document.querySelector("#countryInput").value;
  const topic = document.querySelector("#topicInput").value;
  apiStatus.textContent = isEnglishMode() ? "AI agents running..." : "AI 智能体运行中...";
  studioOutput.textContent = isEnglishMode()
    ? "Researching sources, structuring the framework, generating comic scripts and assessment questions..."
    : "正在研究资料、整理框架、生成漫画脚本和测评题...";

  try {
    if (window.__DATASET_PACK__) {
      const pack = window.__DATASET_PACK__;
      apiStatus.textContent = isEnglishMode() ? "Preview generated; not published" : "内容包预览已生成（未发布）";
      studioOutput.textContent = JSON.stringify(
        isEnglishMode()
          ? {
              Country: country,
              Topic: topic,
              Dataset: pack.meta.name,
              Version: pack.meta.version,
              Summary: `${pack.meta.counts.canonical_insights} insights, ${pack.meta.counts.scenario_units} scenarios, and ${pack.meta.counts.quiz_items} quiz items are available as a preview. Publish requires review.`,
              Framework: pack.modules.map((item) => `${item.id} ${item.title_en || item.title}`),
              LearningCards: pack.cards.slice(0, 6).map((card) => ({
                Title: card.title_en || card.title,
                Category: translateText(card.category),
                ActionTip: card.tip_en || card.tip
              })),
              KeyCulturalRisks: pack.risks.slice(0, 6).map((risk) => risk.title_en || risk.title_zh),
              RecommendedActions: pack.risks.slice(0, 4).map((risk) => risk.recommended_behavior_en || risk.recommended_behavior_zh)
            }
          : {
              国家: country,
              主题: topic,
              数据集: pack.meta.name,
              版本: pack.meta.version,
              内容摘要: `${pack.meta.counts.canonical_insights} 条洞察、${pack.meta.counts.scenario_units} 条场景、${pack.meta.counts.quiz_items} 道题已生成预览；发布前需要人工审核。`,
              知识框架: pack.modules.map((item) => `${item.id} ${item.title}`),
              学习卡片: pack.cards.slice(0, 6).map((card) => ({
                标题: card.title,
                分类: card.category,
                行动建议: card.tip
              })),
              主要文化风险: pack.risks.slice(0, 6).map((risk) => risk.title_zh),
              建议行动: pack.risks.slice(0, 4).map((risk) => risk.recommended_behavior_zh)
            },
        null,
        2
      );
      return;
    }

    const response = await fetch("/api/generate-content", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ country, topic })
    });
    const result = await response.json();
    apiStatus.textContent = result.source === "openai"
      ? (isEnglishMode() ? "AI generated; pending review" : "AI 已生成，待审核")
      : (isEnglishMode() ? "Preview ready; not published" : "预览已生成，未发布");
    studioOutput.textContent = formatStudioOutput(result.data);
  } catch (error) {
    apiStatus.textContent = isEnglishMode() ? "Request failed" : "请求失败";
    studioOutput.textContent = error.message;
  }
}

document.addEventListener("click", (event) => {
  const countryButton = event.target.closest("[data-country]");
  if (countryButton) {
    applyCountryPack(countryButton.dataset.country);
    return;
  }

  const languageButton = event.target.closest("[data-language]");
  if (languageButton) {
    activeLang = languageButton.dataset.language === "en" ? "en" : "zh";
    closeCardDetail();
    rerenderLanguage();
    showToast(isEnglishMode() ? "English review mode enabled." : "已切换为中文。");
    return;
  }

  const observationFilterButton = event.target.closest("[data-observation-filter]");
  if (observationFilterButton) {
    activeObservationGroup = observationFilterButton.dataset.observationFilter;
    renderEnterpriseObservations();
    return;
  }

  const observationModuleButton = event.target.closest("[data-observation-module]");
  if (observationModuleButton) {
    const moduleNo = observationModuleButton.dataset.observationModule;
    const moduleIndex = modules.findIndex((moduleItem) => moduleItem.no === moduleNo);
    if (moduleIndex >= 0) {
      activeModuleIndex = moduleIndex;
      activeCardModuleNo = moduleNo;
      renderModules();
      renderModuleDetail();
      renderCards();
      document.querySelector("#map")?.scrollIntoView({ behavior: "smooth", block: "start" });
      window.setTimeout(() => openModulePanel(moduleIndex, observationModuleButton.dataset.observationPanel || "topics"), 250);
    }
    return;
  }

  const targetButton = event.target.closest("[data-target]");
  if (targetButton?.dataset.target === "observations" && !enterpriseObservationsAvailable()) return;
  if (targetButton) {
    const target = document.querySelector(`#${targetButton.dataset.target}`);
    target?.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  const quizButton = event.target.closest(".quiz-box button");
  if (quizButton) {
    const quiz = quizButton.closest(".quiz-box");
    const rawCard = cards[Number(quiz.dataset.card)];
    const card = isEnglishMode() ? cardEnglishReviewCopy(rawCard) : rawCard;
    const selected = Number(quizButton.dataset.option);
    quiz.querySelectorAll("button").forEach((button) => {
      button.classList.remove("correct", "wrong");
      button.removeAttribute("aria-label");
    });
    if (selected === card.answer) {
      quizButton.classList.add("correct");
      quizButton.setAttribute("aria-label", isEnglishMode() ? "Correct answer" : "回答正确");
      recordQuizResult(card, true);
      showToast(isEnglishMode() ? "Correct. This knowledge point has been recorded." : "回答正确，已记录这个知识点。");
    } else {
      quizButton.classList.add("wrong");
      const correctButton = quiz.querySelector(`[data-option="${card.answer}"]`);
      correctButton?.classList.add("correct");
      correctButton?.setAttribute("aria-label", isEnglishMode() ? "Correct answer" : "正确答案");
      recordQuizResult(card, false);
      showToast(isEnglishMode() ? `Incorrect. Correct answer: ${translateText(card.options[card.answer])}` : `答错了，正确答案是：${card.options[card.answer]}`);
    }
    return;
  }

  const detailQuizButton = event.target.closest("[data-detail-option]");
  if (detailQuizButton) {
    const quiz = detailQuizButton.closest("[data-detail-quiz]");
    const rawCard = cards[Number(quiz.dataset.detailQuiz)];
    const card = isEnglishMode() ? cardEnglishReviewCopy(rawCard) : rawCard;
    const selected = Number(detailQuizButton.dataset.detailOption);
    const feedback = quiz.nextElementSibling;

    quiz.querySelectorAll("button").forEach((button) => {
      button.classList.remove("correct", "wrong");
      button.removeAttribute("aria-label");
    });

    if (selected === card.answer) {
      detailQuizButton.classList.add("correct");
      detailQuizButton.setAttribute("aria-label", isEnglishMode() ? "Correct answer" : "回答正确");
      recordQuizResult(card, true);
      feedback.textContent = isEnglishMode() ? `Correct: ${translateText(card.why)}` : `回答正确：${card.why}`;
    } else {
      detailQuizButton.classList.add("wrong");
      detailQuizButton.setAttribute("aria-label", isEnglishMode() ? "Your answer is incorrect" : "你的选择不正确");
      const correctButton = quiz.querySelector(`[data-detail-option="${card.answer}"]`);
      correctButton?.classList.add("correct");
      correctButton?.setAttribute("aria-label", isEnglishMode() ? "Correct answer" : "正确答案");
      recordQuizResult(card, false);
      feedback.textContent = isEnglishMode() ? `Correct answer: ${translateText(card.options[card.answer])}. ${translateText(card.why)}` : `正确答案：${card.options[card.answer]}。${card.why}`;
    }
    return;
  }

  const contentLayerButton = event.target.closest("[data-content-layer-item]");
  if (contentLayerButton) {
    openContentLayerDetail(contentLayerButton.dataset.contentLayerModule, Number(contentLayerButton.dataset.contentLayerItem));
    return;
  }

  const moduleOutputButton = event.target.closest("[data-module-output-index]");
  if (moduleOutputButton) {
    openModuleOutputDetail(
      moduleOutputButton.dataset.moduleOutputModule,
      moduleOutputButton.dataset.moduleOutputPanel,
      Number(moduleOutputButton.dataset.moduleOutputIndex)
    );
    return;
  }

  const dashboardToolButton = event.target.closest("[data-dashboard-tool-index]");
  if (dashboardToolButton) {
    openDashboardToolDetail(Number(dashboardToolButton.dataset.dashboardToolIndex));
    return;
  }

  const modulePanelButton = event.target.closest("[data-module-panel]");
  if (modulePanelButton) {
    activeModuleIndex = Number(modulePanelButton.dataset.moduleIndex);
    activeCardModuleNo = modules[activeModuleIndex]?.no || null;
    activePanelContext = {
      moduleNo: activeCardModuleNo,
      panelType: modulePanelButton.dataset.modulePanel
    };
    renderModules();
    renderModuleDetail();
    renderCards();
    openModulePanel(activeModuleIndex, modulePanelButton.dataset.modulePanel);
    return;
  }

  const moduleButton = event.target.closest("[data-module]");
  if (moduleButton) {
    activeModuleIndex = Number(moduleButton.dataset.module);
    activeCardModuleNo = modules[activeModuleIndex]?.no || null;
    activePanelContext = null;
    renderModules();
    renderModuleDetail();
    renderCards();
    showToast(isEnglishMode() ? `Opened: ${translateText(modules[activeModuleIndex].title)}` : `已打开：${modules[activeModuleIndex].title}`);
    return;
  }

  const filterButton = event.target.closest("[data-filter]");
  if (filterButton) {
    activeModuleIndex = null;
    activeCardModuleNo = null;
    activePanelContext = null;
    activeFilter = filterButton.dataset.filter;
    document.querySelectorAll("[data-filter]").forEach((button) => button.classList.toggle("active", button === filterButton));
    renderModules();
    renderCultureOverview();
    renderCards();
    showToast(isEnglishMode() ? `Switched to ${translateText(activeFilter)} cards` : `已切换到${activeFilter}知识卡片`);
    return;
  }

  const cardOpenButton = event.target.closest("[data-card-open]");
  if (cardOpenButton) {
    const context = cardOpenButton.dataset.cardContextModule
      ? {
          moduleNo: cardOpenButton.dataset.cardContextModule,
          panelType: cardOpenButton.dataset.cardContextPanel
        }
      : null;
    openCardDetail(Number(cardOpenButton.dataset.cardOpen), context);
    return;
  }

  const learningCard = event.target.closest(".learning-card");
  if (learningCard) {
    openCardDetail(Number(learningCard.dataset.cardIndex), null);
    return;
  }

  if (event.target === detailOverlay || event.target.closest("#detailClose")) {
    closeCardDetail();
    return;
  }

  const studioAction = event.target.closest("[data-studio-action]");
  if (studioAction) {
    const isPublish = studioAction.dataset.studioAction === "publish";
    apiStatus.textContent = isPublish
      ? (isEnglishMode() ? "Preview generated; not published" : "预览已生成，未发布")
      : (isEnglishMode() ? "Waiting for learning confirmation" : "等待学习确认");
    showToast(isPublish
      ? (isEnglishMode() ? "Preview generated. Review is required before publishing." : "预览已生成，发布前需要人工审核")
      : (isEnglishMode() ? "Learning progress recorded." : "已记录学习进度"));
  }

  if (event.target.matches("[data-action='reset']")) resetScenario();
});

