async function loadDatasetPack() {
  try {
    const pack = window.__DATASET_PACK__ || (await fetch("./dataset-pack.json").then((response) => {
      if (!response.ok) throw new Error("数据集接口不可用");
      return response.json();
    }));

    const brazilPack = pack.countryPack || {};
    if (brazilPack.modules?.length) {
      countryPacks.brazil = {
        ...countryPacks.brazil,
        ...brazilPack
      };
      modules = brazilPack.modules;
      cards = brazilPack.cards;
      scenario = brazilPack.scenario;
    } else {
      if (pack?.modules?.length) modules = pack.modules;
      if (pack?.cards?.length) cards = pack.cards;
      if (pack?.scenario?.length) scenario = pack.scenario;
      countryPacks.brazil.modules = modules;
      countryPacks.brazil.cards = cards;
      countryPacks.brazil.scenario = scenario;
      countryPacks.brazil.participantText = `${pack.meta.counts.canonical_insights} 条洞察 / ${pack.meta.counts.quiz_items} 道题`;
      countryPacks.brazil.risks = pack.risks.slice(0, 6).map((risk) => risk.title_zh);
      countryPacks.brazil.recommendations = pack.recommendations.slice(0, 6);
    }

    datasetMeta = pack.meta;
    apiStatus.textContent = "巴西内容包已更新；当前页面仍保持所选国家";
  } catch (error) {
    console.warn(error);
    apiStatus.textContent = "使用内置演示内容";
  }
}

